/**
 * CEPT campus canopy-height extraction — Tier 1 deployment validation
 * ======================================================================
 *
 * WHY THIS SCRIPT EXISTS
 * -----------------------
 * The regional height -> biomass curve (agbd = 0.5326 * rh98^1.8307,
 * spatial-CV R^2 0.92, fit in src/fit_height_biomass_curve.py) was
 * calibrated entirely from GEDI shots. The new architecture explicitly
 * does NOT use GEDI at prediction sites -- Tier 1 (mature canopy) uses a
 * published wall-to-wall canopy-height map instead. This script gets that
 * height for the 537 CEPT cells so src/validate_curve_at_cept.py can run
 * the curve through Tier 1's actual deployment path (published CHM, not
 * GEDI) and compare the predicted total against CEPT's known 978 Mg field
 * census -- the same honest, no-GEDI-at-the-site test the architecture
 * exists to pass.
 *
 * HEIGHT SOURCE: ETH Global Canopy Height 2020 (Lang et al. 2022),
 * 'users/nlang/ETH_GlobalCanopyHeight_2020_10m_v1', 10 m resolution --
 * the asset ID given directly for this step. This script prints the
 * asset's real band names before selecting anything (same discipline as
 * every GEDI band-name check earlier in this project) rather than
 * assuming a band name or count.
 *
 * IMPORTANT CAVEAT (flag, not fix): the power-law curve was calibrated
 * against GEDI's rh98 (98th-percentile relative height from lidar full-
 * waveform returns). This CHM measures top-of-canopy height via a
 * different sensor and methodology (Sentinel-2 + GEDI-trained deep
 * learning model, per Lang et al.). Both approximate "canopy top height
 * in meters," but they are not guaranteed to be numerically identical or
 * cross-calibrated. Applying the rh98-fitted curve to this CHM's height
 * values assumes they're close enough to be interchangeable -- that
 * assumption is exactly what this validation step tests, not something
 * already proven.
 *
 * THIS SCRIPT DOES ONLY HEIGHT EXTRACTION. It samples canopy height at
 * the 537 CEPT cell points and exports a CSV (cell_id + canopy_height_m).
 * No curve application, no biomass prediction, no comparison to the
 * 978 Mg figure happens here -- that's src/validate_curve_at_cept.py,
 * once this CSV exists. AGB/AGB_kg/AGB_Mg_ha from
 * data/raw/grid_cells_for_GEE.csv never enters this script, so there is
 * no way for ground truth to leak into the height values.
 *
 * No tiling / TEST_MODE here (same reasoning as
 * gee/cept_feature_extraction.js): CEPT is 537 points over ~21.5 ha,
 * nowhere near GEE's per-operation size limit.
 *
 * CEPT_CELL_ROWS below is identical to the array in
 * gee/cept_feature_extraction.js (same 537 cells, same cell_id/lat/lon) --
 * copied rather than shared, since GEE scripts can't import each other.
 */

