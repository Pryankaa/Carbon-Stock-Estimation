/**
 * CEPT campus Sentinel-2 feature extraction — ground-truth validation
 * ======================================================================
 *
 * WHY THIS SCRIPT EXISTS
 * -----------------------
 * The trained biomass model (src/train_biomass_model.py) was fit on GEDI
 * shots paired with Sentinel-2 features extracted by
 * gee/gedi_s2_training_extract.js. CEPT University campus, Ahmedabad, has
 * a full field census that no satellite ever touched: 3,261 individually
 * measured trees, 978 Mg AGB over 537 grid cells (~21.5 ha, ~46 Mg/ha).
 * Applying the trained model to CEPT and comparing its predicted total
 * against that 978 Mg is the honest end-to-end test of the whole
 * GEDI -> Sentinel-2 method (see CLAUDE.md "Immediate next task").
 *
 * THIS SCRIPT DOES ONLY FEATURE EXTRACTION. It samples the exact same
 * Sentinel-2 features the model was trained on, at the 537 CEPT cell
 * points, and exports them to a CSV (cell_id + features). No model, no
 * prediction, no comparison to the 978 Mg figure happens here — that's a
 * separate Python step, once this CSV exists. AGB/AGB_kg/AGB_Mg_ha from
 * data/raw/grid_cells_for_GEE.csv never enters this script at all, so
 * there is no way for ground truth to leak into the features.
 *
 * FEATURE DEFINITIONS MUST MATCH TRAINING EXACTLY, OR THE COMPARISON IS
 * INVALID. Section 2 below — the two seasonal windows, the years pooled
 * into them, Cloud Score+ masking, the NDVI/EVI formulas, which
 * composite the reflectance bands come from — is copied verbatim from
 * gee/gedi_s2_training_extract.js's own section 2. If that script's
 * feature logic ever changes, this one must change with it, by hand;
 * nothing here is imported/shared automatically (GEE scripts can't
 * import each other).
 *
 * No tiling / TEST_MODE here (unlike the regional training extractor):
 * CEPT is inherently tiny — 537 points over ~21.5 ha — so a single
 * .sampleRegions() call is nowhere near GEE's per-operation size limit
 * that forced tiling on the ~3.6M-shot regional export.
 *
 * CEPT_CELL_ROWS below is data/raw/grid_cells_for_GEE.csv's cell_id/
 * latitude/longitude columns only (n_trees, AGB_kg, AGB_Mg_ha excluded —
 * see leakage note above), embedded directly so this script needs no
 * separate GEE Table asset upload.
 */

